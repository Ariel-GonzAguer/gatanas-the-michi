export interface AltarSnapshot {
  name: string;
  memory: GatanasMemory;
  alive: boolean;
  awake: boolean;
  lastWatchAt: string | null;
  voiceOk: boolean;
  lives: number;
  purrDrought: number;
  now: string;
}

